// Generates cloudflare/d1/0003_seed.sql: the rows the Supabase migrations themselves insert (entity schemas, plans,
// free / trial limits, modules, add-ons, shop items, coin packs, ad packages, promos, …), read back from a Postgres
// with every migration applied (PGlite, as the tests and scripts/d1-schema.ts do) and written as SQLite INSERTs in the
// D1 storage forms (JSON text, booleans 0/1, ISO-8601 UTC times). Run after scripts/d1-schema.ts:
//   npx tsx scripts/d1-seed.ts
import { readFile, readdir, writeFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { tables } from "../src/lib/d1/tables.gen";

const db = new PGlite();
await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;create schema storage;
  create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}',email_confirmed_at timestamptz);
  create function auth.uid()returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
  create function auth.jwt()returns jsonb language sql stable as $$select jsonb_build_object('email',current_setting('request.jwt.claim.email',true))$$;
  create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
  create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text);alter table storage.objects enable row level security;
  create function storage.foldername(text)returns text[]language sql immutable as $$select string_to_array($1,'/')$$;
  grant usage on schema public,auth,storage to authenticated,anon,service_role;grant execute on all functions in schema auth to authenticated,anon,service_role;`);
for (const f of (await readdir("supabase/migrations")).sort())
  await db.exec((await readFile("supabase/migrations/" + f, "utf8")).replace("create extension if not exists pgcrypto;", ""));

const types = new Map(
  (await db.query<{ table_name: string; column_name: string; udt_name: string }>(`select table_name,column_name,udt_name from information_schema.columns where table_schema='public'`)).rows.map((c) => [
    `${c.table_name}.${c.column_name}`,
    c.udt_name,
  ]),
);
const lit = (v: unknown): string => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
/** A value from row_to_json → its D1 form for this column. */
function d1Value(table: string, col: string, v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  const m = tables[table],
    udt = types.get(`${table}.${col}`) || "";
  if (m.json.includes(col) || udt.startsWith("_")) return lit(JSON.stringify(v));
  if (m.bool.includes(col) || udt === "bool") return v ? "1" : "0";
  if (udt === "timestamptz" || udt === "timestamp") return lit(new Date(String(v)).toISOString());
  if (typeof v === "object") return lit(JSON.stringify(v));
  return lit(v);
}

const out: string[] = [
  "-- Generated by scripts/d1-seed.ts from supabase/migrations (do not edit by hand): the rows the migrations insert.",
  "PRAGMA defer_foreign_keys = ON;",
  "",
];
let total = 0;
const seeded: string[] = [];
for (const table of Object.keys(tables).sort()) {
  const exists = (await db.query<{ n: number }>(`select count(*)::int n from information_schema.tables where table_schema='public' and table_name=$1`, [table])).rows[0].n;
  if (!exists) continue;
  const rows = (await db.query<{ r: Record<string, unknown> }>(`select row_to_json(t) r from public."${table}" t`)).rows.map((x) => x.r);
  if (!rows.length) continue;
  const cols = tables[table].columns.filter((c) => c in rows[0]);
  for (const r of rows) out.push(`INSERT INTO "${table}" (${cols.map((c) => `"${c}"`).join(", ")}) VALUES (${cols.map((c) => d1Value(table, c, r[c])).join(", ")});`);
  out.push("");
  total += rows.length;
  seeded.push(`${table} (${rows.length})`);
}
await writeFile("cloudflare/d1/0003_seed.sql", out.join("\n"));
console.log(`0003_seed.sql: ${total} rows — ${seeded.join(", ")}`);
await db.close();
