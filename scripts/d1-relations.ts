// Reads the primary keys and foreign keys of cloudflare/d1/0001_schema.sql into src/lib/d1/relations.gen.ts, which the
// Supabase-shaped client (postgrest.ts) uses for embeds (`companies(name)`) and default upsert targets.
// Run after scripts/d1-schema.ts: npx tsx scripts/d1-relations.ts
import { readFileSync, writeFileSync } from "node:fs";

const sql = readFileSync("cloudflare/d1/0001_schema.sql", "utf8");
const names = (s: string) => s.split(",").map((x) => x.trim().replace(/^"|"$/g, ""));
const out: Record<string, { pk: string[]; fks: { cols: string[]; table: string; refs: string[] }[] }> = {};
for (const m of sql.matchAll(/CREATE TABLE "([a-z_0-9]+)" \(([\s\S]*?)\n\);/g)) {
  const [, table, body] = m;
  const pk = /PRIMARY KEY \(([^)]*)\)/.exec(body);
  out[table] = {
    pk: pk ? names(pk[1]) : [],
    fks: [...body.matchAll(/FOREIGN KEY \(([^)]*)\) REFERENCES "([a-z_0-9]+)"\(([^)]*)\)/g)].map((f) => ({ cols: names(f[1]), table: f[2], refs: names(f[3]) })),
  };
}
writeFileSync(
  "src/lib/d1/relations.gen.ts",
  `// Generated by scripts/d1-relations.ts from cloudflare/d1/0001_schema.sql: do not edit by hand.\nexport type Relations = { pk: string[]; fks: { cols: string[]; table: string; refs: string[] }[] };\nexport const relations: Record<string, Relations> = ${JSON.stringify(out)};\n`,
);
console.log(Object.keys(out).length, "tables");
