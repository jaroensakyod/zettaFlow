// PromptPay (Thai QR Payment, EMVCo merchant-presented) payload + a tiny QR encoder so the top-up
// dialog can show a scannable QR without a payment gateway or a new dependency.
// Payload: 00 format · 01 POI (11 static / 12 with amount) · 29 PromptPay (AID + mobile/ID/e-wallet)
//          · 58 country · 53 currency 764 · 54 amount · 63 CRC16-CCITT (poly 0x1021, init 0xFFFF).

const field = (id: string, value: string) => id + String(value.length).padStart(2, "0") + value;

/** CRC-16/CCITT-FALSE as 4 upper-case hex digits (the value of EMVCo tag 63). */
export function crc16(text: string): string {
  let crc = 0xffff;
  for (const byte of new TextEncoder().encode(text)) {
    crc ^= byte << 8;
    for (let i = 0; i < 8; i++) crc = crc & 0x8000 ? ((crc << 1) ^ 0x1021) & 0xffff : (crc << 1) & 0xffff;
  }
  return crc.toString(16).toUpperCase().padStart(4, "0");
}

/** Builds the PromptPay payload for a mobile number (10 digits), national/tax ID (13) or e-wallet ID (15). */
export function promptPayPayload(target: string, amount?: number): string {
  const id = target.replace(/\D/g, "");
  let account: string;
  if (id.length >= 13) account = field(id.length >= 15 ? "03" : "02", id);
  else if (/^0\d{9}$/.test(id)) account = field("01", "0066" + id.slice(1));
  else if (/^66\d{9}$/.test(id)) account = field("01", "00" + id);
  else throw new Error("PromptPay ID ต้องเป็นเบอร์มือถือ 10 หลัก เลขประจำตัว 13 หลัก หรือ e-Wallet 15 หลัก");
  const withAmount = amount !== undefined && amount > 0;
  const body =
    field("00", "01") +
    field("01", withAmount ? "12" : "11") +
    field("29", field("00", "A000000677010111") + account) +
    field("58", "TH") +
    field("53", "764") +
    (withAmount ? field("54", amount.toFixed(2)) : "") +
    "6304";
  return body + crc16(body);
}

